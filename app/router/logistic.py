"""
Logistic regression router — the simplest baseline (FR-3.5).

Trained on labels generated by running both small and large models
on a query set and comparing quality (with a judge).

Traceability: FR-3.4, FR-3.5
Build Plan: Step 10
"""

import pickle
from pathlib import Path
import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.calibration import CalibratedClassifierCV

from config.config import load_config
from app.router.features import RouterFeatures


class LogisticRouter:
    """
    Logistic regression model router.

    Usage:
        # Training (offline):
        router = LogisticRouter()
        router.train(features_matrix, labels)  # labels: 1=large needed, 0=small ok
        router.save()

        # Inference (in the proxy):
        router = LogisticRouter()
        router.load()
        p_large = router.predict(features)
    """

    def __init__(self):
        config = load_config()
        self.model_path = config.router.model_path
        self.threshold = config.router.threshold
        self.model: LogisticRegression | None = None
        self._is_trained = False

    def train(self, X: np.ndarray, y: np.ndarray) -> dict:
        """
        Train the logistic regression router.

        Args:
            X: Feature matrix, shape (n_samples, n_features).
               Each row is RouterFeatures.to_vector().
            y: Labels, shape (n_samples,).
               1 = large model needed, 0 = small model sufficient.

        Returns:
            Training metrics (accuracy, coefficients).
        """
        # CalibratedClassifierCV ensures predict_proba is calibrated
        # (Lesson 7, Section 9) — verify with a reliability diagram offline
        base = LogisticRegression(max_iter=1000, C=1.0)
        self.model = CalibratedClassifierCV(base, cv=3, method="sigmoid")
        self.model.fit(X, y)
        self._is_trained = True

        # Training accuracy
        predictions = self.model.predict(X)
        accuracy = np.mean(predictions == y)

        return {
            "accuracy": float(accuracy),
            "n_samples": len(y),
            "n_features": X.shape[1],
        }

    def predict(self, features: RouterFeatures) -> float:
        """
        Predict P(large_needed) for a single query.

        Returns:
            Float in [0, 1]. Compare against config.router.threshold
            to make the routing decision.
        """
        if not self._is_trained:
            raise RuntimeError(
                "Router not trained. Run the label generation script "
                "(scripts/generate_router_labels.py) first."
            )

        x = features.to_vector().reshape(1, -1)
        p_large = self.model.predict_proba(x)[0][1]  # probability of class 1 (large needed)
        return float(p_large)

    def save(self) -> None:
        """Save trained model to disk."""
        if not self._is_trained:
            raise RuntimeError("Cannot save untrained model.")
        Path(self.model_path).parent.mkdir(parents=True, exist_ok=True)
        with open(self.model_path, "wb") as f:
            pickle.dump(self.model, f)

    def load(self) -> None:
        """Load trained model from disk."""
        path = Path(self.model_path)
        if not path.exists():
            raise FileNotFoundError(
                f"Router model not found at {self.model_path}. "
                f"Train it first with scripts/generate_router_labels.py"
            )
        with open(path, "rb") as f:
            self.model = pickle.load(f)
        self._is_trained = True